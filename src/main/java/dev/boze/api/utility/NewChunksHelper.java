package dev.boze.api.utility;

import dev.boze.api.internal.Instances;

/**
 * Read-only access to the chunks classified by the client's NewChunks module.
 * <p>
 * <b>Threading:</b> call these methods from the client thread only, for example from an
 * {@code EventTick} handler. {@link #getAge}, {@link #getDetail} and the marks passed to
 * {@link #forEachMarked} do not allocate. A radius covering more chunks than there are marks
 * allocates a small iterator per call.
 * </p>
 * <p>
 * <b>Collection:</b> the NewChunks module must be enabled, which you can check with
 * {@code ModuleManager.getClientModule("NewChunks").getState()}. While it is off, {@link #getAge}
 * and {@link #getDetail} return {@code null} and {@link #forEachMarked} reports nothing, the same
 * as for a chunk that has no mark. Classification happens when the server sends a chunk, so chunks
 * already loaded when the module is enabled stay unclassified until the server sends them again.
 * The module's render settings have no effect on collection.
 * </p>
 * <p>
 * <b>Lifetime:</b> marks are kept in memory only and nothing is saved, so they cover what was seen
 * since the module was enabled in the current world. Only the current world and dimension are
 * reported. Marks are dropped when the module is disabled, by the newchunks clear command, on joining
 * a server and on a dimension change, so returning to a dimension starts empty. Chunks that arrive
 * during a dimension change can be lost with the old marks and stay unclassified. Within a world,
 * marks outlive chunk unloading, and a chunk keeps its first classification.
 * </p>
 * <p>
 * <b>Detection:</b> marks are heuristics over chunk data as the server sends it, mostly block
 * palette ordering, so {@link ChunkAge#NEW} and {@link ChunkAge#OLD} are likely, not certain.
 * A server that rewrites or regenerates chunk data can change the results.
 * </p>
 * <ul>
 *   <li>Overworld: NEW when the first non-empty section's palette starts with air, or when at
 *   least 51% of non-empty sections have a fresh-looking palette.</li>
 *   <li>Nether: NEW only when the first non-empty section's palette starts with air.</li>
 *   <li>End: NEW only when a non-empty section's biome palette starts with plains.</li>
 *   <li>Anything else received is OLD, so OLD means "no evidence of being new". This includes
 *   chunks with only air, such as the void between End islands, which makes the End's OLD marks
 *   weak evidence of earlier visits.</li>
 *   <li>{@link ChunkAge#OLD} also covers {@link ChunkDetail#LEGACY} and
 *   {@link ChunkDetail#UPDATING}, and a chunk that looks updating is never NEW. With DetectUpdating
 *   off, nothing is reported as {@link ChunkDetail#UPDATING} and those chunks are judged by the
 *   other rules. With a DetectLegacy setting off, that dimension reports no
 *   {@link ChunkDetail#LEGACY}.</li>
 * </ul>
 * <p>
 * A received chunk stays unclassified only if its data fails to parse, or if outside the End it
 * looks new while legacy detection also calls it legacy. The second case is most likely in the
 * Nether, where the default DetectLegacy calls a chunk legacy when its lowest eight sections
 * contain none of the post-1.16 blocks it looks for. Turning off the matching DetectLegacy setting
 * makes such a chunk NEW. How often this happens depends on the terrain and has not been measured.
 * The End requires the same biome evidence for NEW with or without its setting.
 * </p>
 */
public final class NewChunksHelper {

    private NewChunksHelper() {
    }

    /**
     * The classification of a chunk. Unclassified chunks have no age and are never reported as
     * either value.
     */
    public enum ChunkAge {
        /** The chunk data looks freshly generated. */
        NEW,
        /** The chunk data shows no evidence of being freshly generated. */
        OLD
    }

    /**
     * The classification of a chunk as the NewChunks module shows it. {@link #NEW} is
     * {@link ChunkAge#NEW}, and every other value is {@link ChunkAge#OLD}.
     */
    public enum ChunkDetail {
        /** The chunk data looks freshly generated. */
        NEW,
        /** No evidence of being new, and not {@link #UPDATING} or {@link #LEGACY}. */
        OLD,
        /** The chunk looks like it is being upgraded from older terrain. */
        UPDATING,
        /** The chunk looks like it was generated by an older game version. */
        LEGACY
    }

    /**
     * Gets the age of a chunk in the current world and dimension.
     *
     * @param chunkX The chunk X coordinate
     * @param chunkZ The chunk Z coordinate
     * @return The age, or {@code null} if the chunk is unclassified or NewChunks is off
     */
    public static ChunkAge getAge(int chunkX, int chunkZ) {
        return Instances.getNewChunks().getAge(chunkX, chunkZ);
    }

    /**
     * Gets the detailed classification of a chunk in the current world and dimension.
     *
     * @param chunkX The chunk X coordinate
     * @param chunkZ The chunk Z coordinate
     * @return The detail, or {@code null} if the chunk is unclassified or NewChunks is off
     */
    public static ChunkDetail getDetail(int chunkX, int chunkZ) {
        return Instances.getNewChunks().getDetail(chunkX, chunkZ);
    }

    /**
     * Reports every classified chunk within a square radius, in the current world and dimension.
     * <p>
     * The order is unspecified. The scan blocks incoming chunk classification while it runs, so
     * keep the consumer short, and do not toggle NewChunks from it.
     * </p>
     *
     * @param centerChunkX The chunk X coordinate of the center
     * @param centerChunkZ The chunk Z coordinate of the center
     * @param radius The radius in chunks, where 0 covers only the center chunk. A negative radius
     *               reports nothing
     * @param consumer Receives each classified chunk
     */
    public static void forEachMarked(int centerChunkX, int centerChunkZ, int radius, MarkedChunkConsumer consumer) {
        Instances.getNewChunks().forEachMarked(centerChunkX, centerChunkZ, radius, consumer);
    }

    /**
     * Receives a classified chunk from {@link #forEachMarked}.
     */
    @FunctionalInterface
    public interface MarkedChunkConsumer {
        void accept(int chunkX, int chunkZ, ChunkAge age, ChunkDetail detail);
    }
}
